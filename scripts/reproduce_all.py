from __future__ import annotations

"""Run the complete repository workflow from a clean generated-output state."""

import argparse
from pathlib import Path
import shutil
import subprocess
import sys
from typing import Iterable

ROOT = Path(__file__).resolve().parents[1]
LOG_DIR = ROOT / "results" / "logs"
LOG_PATH = LOG_DIR / "reproduction.log"


def _remove_files(patterns: Iterable[str]) -> None:
    for pattern in patterns:
        for path in ROOT.glob(pattern):
            if path.is_file() or path.is_symlink():
                path.unlink()
            elif path.is_dir():
                shutil.rmtree(path)


def clean_generated_outputs() -> None:
    """Remove only files generated by tests and experiment scripts."""
    _remove_files(
        [
            ".pytest_cache",
            "build",
            "dist",
            "*.egg-info",
            "src/*.egg-info",
            "data/processed/*.csv",
            "results/tables/*",
            "results/logs/*.log",
            "figures/*.pdf",
            "figures/*.png",
            "RESULTS_SUMMARY.md",
            "REPRODUCIBILITY_MANIFEST.txt",
            "results/run_metadata.json",
            "results/reproduction_check.json",
        ]
    )
    (ROOT / "data" / "processed").mkdir(parents=True, exist_ok=True)
    (ROOT / "results" / "tables").mkdir(parents=True, exist_ok=True)
    LOG_DIR.mkdir(parents=True, exist_ok=True)
    (ROOT / "figures").mkdir(parents=True, exist_ok=True)


def run_command(command: list[str], log_handle) -> None:
    rendered = " ".join(command)
    banner = f"\n$ {rendered}\n"
    print(banner, end="", flush=True)
    log_handle.write(banner)
    log_handle.flush()

    process = subprocess.Popen(
        command,
        cwd=ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
    )
    assert process.stdout is not None
    for line in process.stdout:
        print(line, end="", flush=True)
        log_handle.write(line)
    return_code = process.wait()
    log_handle.flush()
    if return_code != 0:
        raise subprocess.CalledProcessError(return_code, command)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--mode",
        choices=["full", "validation"],
        default="full",
        help="Run all experiments, or only tests and mathematical validation.",
    )
    parser.add_argument(
        "--no-clean",
        action="store_true",
        help="Keep existing generated outputs before running.",
    )
    args = parser.parse_args()

    if not args.no_clean:
        clean_generated_outputs()
    else:
        LOG_DIR.mkdir(parents=True, exist_ok=True)

    commands: list[list[str]] = [
        [sys.executable, "-m", "pytest", "-q"],
    ]
    if args.mode == "validation":
        commands.extend(
            [
                [sys.executable, "scripts/run_all_experiments.py", "--experiment", "validation"],
                [sys.executable, "scripts/write_run_metadata.py", "--mode", "validation"],
                [sys.executable, "scripts/check_outputs.py", "--mode", "validation"],
                [sys.executable, "scripts/write_manifest.py"],
            ]
        )
    else:
        commands.extend(
            [
                [sys.executable, "scripts/run_all_experiments.py", "--experiment", "all"],
                [sys.executable, "scripts/make_figures.py"],
                [sys.executable, "scripts/make_www_summary_figure.py"],
                [sys.executable, "scripts/make_tables.py"],
                [sys.executable, "scripts/summarize_results.py"],
                [sys.executable, "scripts/write_run_metadata.py", "--mode", "full"],
                [sys.executable, "scripts/check_outputs.py", "--mode", "full"],
                [sys.executable, "scripts/write_manifest.py"],
            ]
        )

    LOG_DIR.mkdir(parents=True, exist_ok=True)
    with LOG_PATH.open("w", encoding="utf-8") as log_handle:
        log_handle.write(f"Repository root: {ROOT}\nMode: {args.mode}\n")
        for command in commands:
            run_command(command, log_handle)

    print(f"\nReproduction workflow completed. Log: {LOG_PATH}", flush=True)


if __name__ == "__main__":
    main()
